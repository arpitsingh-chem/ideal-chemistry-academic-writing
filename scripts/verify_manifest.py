#!/usr/bin/env python3
"""Generate or verify ``MANIFEST.md`` (SHA-256 of every tracked file).

The manifest exists so that a reviewer can answer one question without trusting
anyone: *is the tree I have the tree that was tested?* It is not a security
boundary — a hostile contributor can regenerate it — it is an integrity and
reproducibility record for an honest one.

Usage
-----
    python3 scripts/verify_manifest.py            # verify against MANIFEST.md
    python3 scripts/verify_manifest.py --write    # (re)write MANIFEST.md
    python3 scripts/verify_manifest.py --json     # machine-readable verification

Exit codes: 0 consistent · 1 mismatch/missing · 2 usage error.

Deliberately excluded from the manifest: VCS internals, caches, build output, the
manifest itself, and any local research database. Everything else is hashed,
including binary assets, so a silently-edited figure or dataset is caught.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "MANIFEST.md"

EXCLUDED_DIRS = {
    ".git", "__pycache__", ".pytest_cache", ".ruff_cache", ".mypy_cache",
    "build", "dist", ".venv", "venv", "node_modules", ".idea", ".vscode",
}
EXCLUDED_SUFFIXES = {".pyc", ".pyo", ".orig", ".rej", ".sqlite3", ".sqlite3-journal", ".db"}
EXCLUDED_NAMES = {"MANIFEST.md", ".DS_Store", "refcache.json"}


def _iter_files() -> list[Path]:
    """Every file that should be covered by the manifest, in stable order."""
    out: list[Path] = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT)
        if any(part in EXCLUDED_DIRS for part in rel.parts):
            continue
        if path.suffix in EXCLUDED_SUFFIXES or path.name in EXCLUDED_NAMES:
            continue
        out.append(rel)
    return out


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def compute() -> dict[str, tuple[str, int]]:
    return {rel.as_posix(): (sha256(ROOT / rel), (ROOT / rel).stat().st_size)
            for rel in _iter_files()}


def _git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True,
                              text=True, check=False).stdout.strip()
    except OSError:                       # git not installed
        return ""


def write_manifest() -> int:
    entries = compute()
    total_bytes = sum(size for _, size in entries.values())
    commit = _git("rev-parse", "--short", "HEAD") or "unknown"
    branch = _git("rev-parse", "--abbrev-ref", "HEAD") or "unknown"
    lines = [
        "# MANIFEST",
        "",
        "SHA-256 of every tracked file in this tree, generated by",
        "[`scripts/verify_manifest.py`](scripts/verify_manifest.py).",
        "",
        f"* commit: `{commit}` on `{branch}`",
        f"* files: **{len(entries)}**",
        f"* bytes: **{total_bytes:,}**",
        "",
        "Verify with:",
        "",
        "```bash",
        "python3 scripts/verify_manifest.py",
        "```",
        "",
        "A mismatch means the file differs from the state recorded here — expected if you",
        "are on a later commit (regenerate with `--write`), and worth investigating if you",
        "are on the commit named above.",
        "",
        "Excluded: `.git/`, caches, `build/`, `dist/`, `*.sqlite3`, `refcache.json` and this",
        "file. Everything else is hashed, **including binary assets** (figures, PDFs, the",
        "DOCX template, the data snapshot), so a silently edited dataset is detected.",
        "",
        "| file | bytes | sha256 |",
        "|---|---:|---|",
    ]
    for rel, (digest, size) in entries.items():
        lines.append(f"| `{rel}` | {size:,} | `{digest}` |")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)}: {len(entries)} files, {total_bytes:,} bytes")
    return 0


def parse_manifest() -> dict[str, str]:
    recorded: dict[str, str] = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| `"):
            continue
        parts = [p.strip() for p in line.strip("|").split("|")]
        if len(parts) != 3:
            continue
        name = parts[0].strip("`")
        digest = parts[2].strip("`")
        if len(digest) == 64:
            recorded[name] = digest
    return recorded


def verify(as_json: bool = False) -> int:
    if not MANIFEST.exists():
        print("MANIFEST.md is missing — run with --write", file=sys.stderr)
        return 2
    recorded = parse_manifest()
    current = compute()

    missing = sorted(set(recorded) - set(current))
    added = sorted(set(current) - set(recorded))
    changed = sorted(p for p in set(recorded) & set(current) if recorded[p] != current[p][0])

    if as_json:
        print(json.dumps({"ok": not (missing or changed), "changed": changed,
                          "missing": missing, "added": added,
                          "files": len(current)}, indent=2))
    else:
        print(f"manifest: {len(recorded)} recorded, {len(current)} present")
        for label, items in (("CHANGED", changed), ("MISSING", missing), ("NEW (not in manifest)", added)):
            if items:
                print(f"  {label}: {len(items)}")
                for name in items[:20]:
                    print(f"    {name}")
                if len(items) > 20:
                    print(f"    … and {len(items) - 20} more")
        print("OK — tree matches the manifest" if not (changed or missing)
              else "FAIL — the tree differs from the manifest (run --write if intentional)")

    return 0 if not (changed or missing) else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="regenerate MANIFEST.md")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    args = parser.parse_args(argv)
    return write_manifest() if args.write else verify(as_json=args.json)


if __name__ == "__main__":
    raise SystemExit(main())
